/**
 * Bundles the DOM serializer into the standalone script the iOS Share
 * Extension runs inside Safari.
 *
 * Safari hands the extension a single classic script that must expose a
 * global object with a `run` method. Generating it from src/lib/domSnapshot.ts
 * keeps one implementation instead of two that drift apart.
 */
import { build } from 'vite'
import { writeFileSync, rmSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const OUT_DIR = 'ios/native/.preprocess-build'
const TARGET = 'ios/native/share-preprocess.js'

await build({
  configFile: false,
  logLevel: 'warn',
  build: {
    outDir: OUT_DIR,
    emptyOutDir: true,
    lib: {
      entry: 'src/lib/domSnapshot.ts',
      formats: ['iife'],
      name: 'InspoSnapshot',
      fileName: () => 'snapshot.js',
    },
    minify: false,
  },
})

const bundled = readFileSync(join(OUT_DIR, 'snapshot.js'), 'utf8')
rmSync(OUT_DIR, { recursive: true, force: true })

const wrapper = `// GENERATED by scripts/build-preprocess.mjs - do not edit by hand.
// Run \`npm run build:preprocess\` after changing src/lib/domSnapshot.ts.
${bundled}

/**
 * Safari runs this in the page and passes whatever we hand to
 * completionFunction back to the Share Extension.
 */
var InspoPreprocess = function () {};
InspoPreprocess.prototype = {
  run: function (args) {
    var payload = null;
    try {
      payload = InspoSnapshot.snapshotDocument(document);
    } catch (e) {
      // A page we cannot serialize must still share its screenshot.
      payload = null;
    }
    args.completionFunction({ snapshot: payload ? JSON.stringify(payload) : null });
  },
  finalize: function () {},
};

var ExtensionPreprocessingJS = new InspoPreprocess();
`

writeFileSync(TARGET, wrapper)
console.log(`wrote ${TARGET} (${(wrapper.length / 1024).toFixed(1)} kB)`)
